CREATE DATABASE IF NOT EXISTS qlsv;
USE qlsv;

CREATE TABLE IF NOT EXISTS Khoa (
    MaKhoa VARCHAR(10) PRIMARY KEY,
    TenKhoa VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Nganh (
    MaNganh VARCHAR(10) PRIMARY KEY,
    TenNganh VARCHAR(100) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    FOREIGN KEY (MaKhoa) REFERENCES Khoa(MaKhoa)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Lop (
    MaLop VARCHAR(20) PRIMARY KEY,
    TenLop VARCHAR(100) NOT NULL,
    MaNganh VARCHAR(10) NOT NULL,
    FOREIGN KEY (MaNganh) REFERENCES Nganh(MaNganh)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MonHoc (
    MaMH VARCHAR(10) PRIMARY KEY,
    TenMH VARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS HocKy (
    MaHK VARCHAR(10) PRIMARY KEY,
    TenHK VARCHAR(50) NOT NULL,
    NamHoc VARCHAR(9) NOT NULL
) ENGINE=InnoDB;

ALTER TABLE SinhVien
    ADD COLUMN MaLop VARCHAR(20) NULL,
    ADD CONSTRAINT fk_sinhvien_lop
    FOREIGN KEY (MaLop) REFERENCES Lop(MaLop);

CREATE TABLE IF NOT EXISTS Diem (
    MaSV VARCHAR(20) NOT NULL,
    MaMH VARCHAR(10) NOT NULL,
    MaHK VARCHAR(10) NOT NULL,
    DiemSo DECIMAL(4,2),
    PRIMARY KEY (MaSV, MaMH, MaHK),
    FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV),
    FOREIGN KEY (MaMH) REFERENCES MonHoc(MaMH),
    FOREIGN KEY (MaHK) REFERENCES HocKy(MaHK)
) ENGINE=InnoDB;
